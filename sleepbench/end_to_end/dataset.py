"""
Raw-signal dataset for the end-to-end baseline.

Unlike the frozen-embedding pipeline, this loads the original 16-channel
HDF5 files instead of pre-computed embeddings. Channels are placed in the
canonical CL ordering (BAS, RESP, EKG, EMG) so the encoder slices them
correctly. Sleep-stage labels are kept on the same temporal grid as the
encoder's output (one label per `chunk_samples / tokens_per_chunk` samples,
e.g. one label per 5 seconds at 128 Hz).
"""

import glob
import os

import h5py
import numpy as np
import pandas as pd
import torch
from loguru import logger
from torch.utils.data import Dataset
from tqdm import tqdm

from ..labels import load_stage_labels


CANONICAL_ORDER = [
    ("BAS", 8),
    ("RESP", 5),
    ("EKG", 1),
    ("EMG", 2),
]
TOTAL_CHANNELS = sum(n for _, n in CANONICAL_ORDER)


def _load_split(split_path):
    import json
    with open(split_path) as f:
        return json.load(f)


def _build_channel_order(hdf5_keys, channel_groups):
    """Return list of channel names in canonical (BAS, RESP, EKG, EMG) order.

    For each modality we keep at most the canonical channel count. Missing
    channels are left as `None` and will be zero-padded by the caller so the
    16-channel layout the model expects is preserved.
    """
    ordered = []
    for modality, n_expected in CANONICAL_ORDER:
        available = [c for c in channel_groups[modality] if c in hdf5_keys]
        # If the recording has more channels than expected, take the first N
        # in the order specified by `channel_groups` (deterministic).
        available = available[:n_expected]
        # Pad with None to reach n_expected.
        ordered.extend(available + [None] * (n_expected - len(available)))
    return ordered


class RawSignalDataset(Dataset):
    """Loads raw 16-channel PSG data + downstream labels for a single recording."""

    def __init__(self, config, channel_groups, split, include_ahi=True, task=None):
        self.config = config
        self.channel_groups = channel_groups
        self.split = split
        self.include_ahi = include_ahi

        # Sampling layout
        self.sampling_freq = int(config["sampling_freq"])  # 128
        self.tokens_per_chunk = int(config["tokens_per_chunk"])  # 60
        self.input_size = int(config["input_size"])  # 640 samples per token
        self.chunk_samples = self.tokens_per_chunk * self.input_size  # 38400

        # Optional cap on total chunks per recording (memory control).
        # `max_chunks_per_recording = 0` means "use the whole recording".
        self.max_chunks_per_recording = int(config.get("max_chunks_per_recording", 0))

        # Labels
        self.df_demographics = pd.read_csv(config["demographics_labels_path"])
        self.df_diagnosis_presence = pd.read_csv(
            os.path.join(config["diagnosis_labels_path"], "is_event.csv")
        )
        self.df_diagnosis_time = pd.read_csv(
            os.path.join(config["diagnosis_labels_path"], "time_to_event.csv")
        )
        self.df_death_presence = pd.read_csv(
            os.path.join(config["death_labels_path"], "is_event.csv"),
            usecols=["Study ID", "death"],
        )
        self.df_death_time = pd.read_csv(
            os.path.join(config["death_labels_path"], "time_to_event.csv"),
            usecols=["Study ID", "death"],
        )

        # AHI / apnea label source. Defaults to the existing AHI behavior:
        # read the continuous AHI CSV and binarize on the fly at threshold 15.
        # Set `config['use_apnea_csv'] = True` and provide
        # `config['apnea_labels_path']` to use a pre-binarized CSV instead
        # (generated by labels/make_apnea_labels.py). The new
        # `apnea_diagnosis/train_apnea.py` script flips this flag; the
        # existing `ahi_diagnosis/train_ahi.py` does not.
        self.apnea_source = None
        if include_ahi:
            if config.get("use_apnea_csv"):
                apnea_path = config.get("apnea_labels_path")
                if not apnea_path:
                    raise ValueError(
                        "use_apnea_csv=True but config['apnea_labels_path'] is empty."
                    )
                self.df_ahi = pd.read_csv(apnea_path)
                missing = {"Study ID", "apnea"} - set(self.df_ahi.columns)
                if missing:
                    raise ValueError(
                        f"apnea_labels_path={apnea_path} is missing columns "
                        f"{sorted(missing)}; expected 'Study ID' and 'apnea'."
                    )
                self.df_ahi["diagnosis"] = self.df_ahi["apnea"].astype(int)
                self.apnea_source = "binary_csv"
            else:
                self.df_ahi = pd.read_csv(config["ahi_labels_path"])
                self.df_ahi["diagnosis"] = self.df_ahi.ahi.apply(
                    lambda x: 1 if x >= 15 else 0
                )
                self.apnea_source = "ahi_threshold_15"
            logger.info(f"[E2E][{split}] apnea label source: {self.apnea_source}")

        # Build the intersection of study IDs that have every label we need.
        # sleep_age needs only age (+ sleep labels below), matching the frozen
        # staging/age pipeline; ahi and death_diagnosis keep the frozen-head
        # eligibility (demographics, diagnoses, death [, AHI]).
        self.task = task
        unique_ids = set(self.df_demographics["Study ID"].values)
        if task != "sleep_age":
            unique_ids = (
                unique_ids
                .intersection(self.df_diagnosis_presence["Study ID"].values)
                .intersection(self.df_diagnosis_time["Study ID"].values)
                .intersection(self.df_death_presence["Study ID"].values)
                .intersection(self.df_death_time["Study ID"].values)
            )
        if include_ahi:
            unique_ids = unique_ids.intersection(self.df_ahi["Study ID"].values)

        # Find sleep-stage label files
        labels_path = config["labels_path"]
        datasets = str(config["dataset"]).split(",")
        label_files = []
        for dataset_name in datasets:
            label_files += glob.glob(
                os.path.join(labels_path, dataset_name, "**", "*.csv"), recursive=True
            )
        labels_dict = {
            os.path.basename(p).split(".")[0]: p for p in label_files
        }
        stage_study_ids = set(labels_dict.keys())

        # Raw-signal HDF5 paths for this split
        splits = _load_split(config["split_path"])
        hdf5_paths = splits[split]
        # read raw PSG from config['raw_data_dir'] (staged copy) and drop
        # recordings found unreadable during staging (config['exclude_ids_path'])
        if config.get("raw_data_dir"):
            hdf5_paths = [os.path.join(config["raw_data_dir"], os.path.basename(p)) for p in hdf5_paths]
        if config.get("exclude_ids_path"):
            with open(config["exclude_ids_path"]) as f:
                bad = set(f.read().split())
            hdf5_paths = [p for p in hdf5_paths if os.path.basename(p).split(".")[0] not in bad]
        hdf5_paths = [p for p in hdf5_paths if os.path.exists(p)]
        hdf5_paths = [p for p in hdf5_paths if os.path.basename(p).split(".")[0] in stage_study_ids]
        hdf5_paths = [p for p in hdf5_paths if os.path.basename(p).split(".")[0] in unique_ids]

        if config.get("max_files"):
            hdf5_paths = hdf5_paths[: config["max_files"]]

        self.index_map = [
            (p, labels_dict[os.path.basename(p).split(".")[0]]) for p in hdf5_paths
        ]
        logger.info(f"[E2E][{split}] usable recordings: {len(self.index_map)}")

        # Pre-index labels by Study ID for O(1) lookup.
        self._demo_idx = self.df_demographics.set_index("Study ID")
        self._diag_pres_idx = self.df_diagnosis_presence.set_index("Study ID")
        self._diag_time_idx = self.df_diagnosis_time.set_index("Study ID")
        self._death_pres_idx = self.df_death_presence.set_index("Study ID")
        self._death_time_idx = self.df_death_time.set_index("Study ID")
        if include_ahi:
            self._ahi_idx = self.df_ahi.set_index("Study ID")

    def __len__(self):
        return len(self.index_map)

    def _log_problem_file(self, hdf5_path, err):
        """Append a corrupted/unreadable file to a problem log (one per dataset
        instance). Workers each have their own log; that's fine."""
        log_path = os.path.join(os.getcwd(), "e2e_problem_hdf5.txt")
        try:
            with open(log_path, "a") as f:
                f.write(f"{hdf5_path}\t{type(err).__name__}: {err}\n")
        except OSError:
            pass

    def _read_recording(self, hdf5_path):
        """Return (x, num_chunks) or None if the file is unusable.

        HDF5 files in the SSC dataset are occasionally truncated or have a
        bad header; the original repo skips them (see
        `comparison/models/dataset.py`) so we do the same here.
        """
        try:
            with h5py.File(hdf5_path, "r") as hf:
                available_keys = list(hf.keys())
                ordered_channels = _build_channel_order(available_keys, self.channel_groups)
                first_present = next((c for c in ordered_channels if c is not None), None)
                if first_present is None:
                    return None
                signal_length = hf[first_present].shape[0]
                num_chunks_full = signal_length // self.chunk_samples
                if num_chunks_full == 0:
                    return None
                if self.max_chunks_per_recording > 0:
                    num_chunks = min(num_chunks_full, self.max_chunks_per_recording)
                else:
                    num_chunks = num_chunks_full
                usable = num_chunks * self.chunk_samples

                x = np.zeros((TOTAL_CHANNELS, usable), dtype=np.float32)
                for i, ch_name in enumerate(ordered_channels):
                    if ch_name is None:
                        continue
                    x[i] = hf[ch_name][:usable]
            return x, num_chunks
        except (OSError, KeyError, ValueError) as err:
            # fail loudly instead of silently substituting another recording
            if self.config.get("strict_io"):
                raise RuntimeError(f"unreadable raw file {hdf5_path}") from err
            logger.warning(f"[E2E] skipping unreadable file {hdf5_path}: {err}")
            self._log_problem_file(hdf5_path, err)
            return None

    def _build_sample(self, real_idx):
        """Return the sample dict for `real_idx`, or None if unreadable."""
        hdf5_path, label_path = self.index_map[real_idx]
        study_id = os.path.basename(hdf5_path).split(".")[0]

        loaded = self._read_recording(hdf5_path)
        if loaded is None:
            return None
        x_data, num_chunks = loaded

        try:
            y_data = load_stage_labels(label_path)  # was labels_df["StageNumber"]
        except (OSError, KeyError, ValueError, pd.errors.ParserError) as err:
            logger.warning(f"[E2E] skipping bad label CSV {label_path}: {err}")
            self._log_problem_file(label_path, err)
            return None

        total_tokens = num_chunks * self.tokens_per_chunk
        if len(y_data) >= total_tokens:
            y_data = y_data[:total_tokens]
        else:
            pad = np.full(total_tokens - len(y_data), fill_value=-1, dtype=y_data.dtype)
            y_data = np.concatenate([y_data, pad])

        if self.task == "sleep_age":  # unused labels (loss weight 0) may be missing
            n_diag = self.df_diagnosis_presence.shape[1] - 1
            z = lambda n: torch.zeros(n, dtype=torch.float32)
            diagnosis_presence = (torch.tensor(self._diag_pres_idx.loc[study_id].values.astype(np.float32))
                                  if study_id in self._diag_pres_idx.index else z(n_diag))
            diagnosis_time = (torch.tensor(self._diag_time_idx.loc[study_id].values.astype(np.float32))
                              if study_id in self._diag_time_idx.index else z(n_diag))
            death_presence = (torch.tensor(np.atleast_1d(self._death_pres_idx.loc[study_id].values).astype(np.float32))
                              if study_id in self._death_pres_idx.index else z(1))
            death_time = (torch.tensor(np.atleast_1d(self._death_time_idx.loc[study_id].values).astype(np.float32))
                          if study_id in self._death_time_idx.index else z(1))
            age = torch.tensor(self._demo_idx.loc[study_id, "Age at Study Date"],
                               dtype=torch.float32).reshape(1) / 100.0
            ahi = torch.zeros(1)
            return {
                "x_raw": torch.from_numpy(x_data), "y_stage": torch.from_numpy(y_data).float(),
                "num_chunks": num_chunks, "diagnosis_presence": diagnosis_presence,
                "diagnosis_time": diagnosis_time, "death_presence": death_presence,
                "death_time": death_time, "age": age, "ahi": ahi, "hdf5_path": hdf5_path,
            }

        try:
            diagnosis_presence = torch.tensor(
                self._diag_pres_idx.loc[study_id].values.astype(np.float32)
            )
            diagnosis_time = torch.tensor(
                self._diag_time_idx.loc[study_id].values.astype(np.float32)
            )
            death_presence = torch.tensor(
                np.atleast_1d(self._death_pres_idx.loc[study_id].values).astype(np.float32)
            )
            death_time = torch.tensor(
                np.atleast_1d(self._death_time_idx.loc[study_id].values).astype(np.float32)
            )
            age = torch.tensor(
                self._demo_idx.loc[study_id, "Age at Study Date"], dtype=torch.float32
            ).reshape(1) / 100.0
            if self.include_ahi:
                ahi = torch.tensor(
                    self._ahi_idx.loc[study_id, "diagnosis"], dtype=torch.float32
                ).reshape(1)
            else:
                ahi = torch.zeros(1)
        except KeyError as err:
            logger.warning(f"[E2E] label lookup failed for {study_id}: {err}")
            self._log_problem_file(hdf5_path, err)
            return None

        return {
            "x_raw": torch.from_numpy(x_data),                # (16, num_chunks * chunk_samples)
            "y_stage": torch.from_numpy(y_data).float(),      # (num_chunks * tokens_per_chunk,)
            "num_chunks": num_chunks,
            "diagnosis_presence": diagnosis_presence,
            "diagnosis_time": diagnosis_time,
            "death_presence": death_presence,
            "death_time": death_time,
            "age": age,
            "ahi": ahi,
            "hdf5_path": hdf5_path,
        }

    def __getitem__(self, idx):
        # Bounded skip-on-error to avoid infinite recursion if many files in a
        # row are bad. Walks `len(dataset)` indices at worst.
        n = len(self.index_map)
        for offset in range(n):
            sample = self._build_sample((idx + offset) % n)
            if sample is not None:
                return sample
        raise RuntimeError(
            f"Every HDF5 file starting from idx={idx} was unreadable; "
            "check e2e_problem_hdf5.txt for the list."
        )


def make_collate_fn(tokens_per_chunk, chunk_samples, max_chunks=None):
    """Collate variable-length recordings into a fixed-shape batch.

    Each item is padded along the temporal dimension to a multiple of
    `chunk_samples`. The returned `chunk_mask` is True for padded chunks
    so the head can ignore them.
    """

    def collate(batch):
        # Discard any None items defensively (shouldn't happen).
        batch = [b for b in batch if b is not None]

        chunk_counts = [int(item["num_chunks"]) for item in batch]
        max_n = max(chunk_counts)
        if max_chunks is not None:
            max_n = min(max_n, int(max_chunks))

        total_samples = max_n * chunk_samples
        total_tokens = max_n * tokens_per_chunk

        b = len(batch)
        x_pad = torch.zeros((b, TOTAL_CHANNELS, total_samples), dtype=torch.float32)
        y_pad = torch.zeros((b, total_tokens), dtype=torch.float32)
        chunk_mask = torch.ones((b, max_n), dtype=torch.bool)  # True = padding

        diagnosis_presence = []
        diagnosis_time = []
        death_presence = []
        death_time = []
        age = []
        ahi = []
        paths = []

        for i, item in enumerate(batch):
            n = min(chunk_counts[i], max_n)
            x_pad[i, :, : n * chunk_samples] = item["x_raw"][:, : n * chunk_samples]
            y_pad[i, : n * tokens_per_chunk] = item["y_stage"][: n * tokens_per_chunk]
            chunk_mask[i, :n] = False

            diagnosis_presence.append(item["diagnosis_presence"])
            diagnosis_time.append(item["diagnosis_time"])
            death_presence.append(item["death_presence"])
            death_time.append(item["death_time"])
            age.append(item["age"])
            ahi.append(item["ahi"])
            paths.append(item["hdf5_path"])

        return {
            "x_raw": x_pad,
            "y_stage": y_pad,
            "chunk_mask": chunk_mask,
            "diagnosis_presence": torch.stack(diagnosis_presence),
            "diagnosis_time": torch.stack(diagnosis_time),
            "death_presence": torch.stack(death_presence),
            "death_time": torch.stack(death_time),
            "age": torch.stack(age),
            "ahi": torch.stack(ahi),
            "hdf5_path": paths,
        }

    return collate
